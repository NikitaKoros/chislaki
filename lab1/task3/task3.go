package main

import (
	"fmt"
	"math"
)

func main() {
	n := 8

	// Полная матрица A (n x n)
	A := [][]float64{
		{15, -8, 0, 0, 0, 0, 0, 0},
		{3, -7, -4, 0, 0, 0, 0, 0},
		{0, -3, 7, 4, 0, 0, 0, 0},
		{0, 0, -4, -9, 3, 0, 0, 0},
		{0, 0, 0, 2, -6, -3, 0, 0},
		{0, 0, 0, 0, -5, 10, 4, 0},
		{0, 0, 0, 0, 0, 3, -8, -2},
		{0, 0, 0, 0, 0, 0, 0, -5},
	}

	// Вектор свободных членов d
	d := []float64{17, -40, -25, -53, -15, 18, -17, -19}

	// Нарезка коэффициентов для метода прогонки
	a := make([]float64, n) // a[i] — поддиагональный элемент в строке i (i >= 1)
	b := make([]float64, n) // b[i] — главная диагональ в строке i
	c := make([]float64, n) // c[i] — наддиагональный элемент в строке i (i <= n-2); c[n-1] = 0

	for i := 0; i < n; i++ {
		b[i] = A[i][i] // главная диагональ

		if i < n-1 {
			c[i] = A[i][i+1] // наддиагональ
		} else {
			c[i] = 0 // последний элемент наддиагонали отсутствует
		}

		if i > 0 {
			a[i] = A[i][i-1] // поддиагональ
		}
		// a[0] остаётся 0 — не используется
	}

	fmt.Println("ПРОВЕРКА УСТОЙЧИВОСТИ МЕТОДА ПРОГОНКИ")

	allStable := true

	// Проверка основного условия для всех строк i = 0, 1, ..., n-1
	for i := 0; i < n; i++ {
		left := math.Abs(b[i])
		right := math.Abs(a[i]) + math.Abs(c[i])
		if left < right {
			fmt.Printf("Условие |b_%d| >= |a_%d| + |c_%d| нарушено: %.2f < %.2f\n", i+1, i+1, i+1, left, right)
			allStable = false
		} else {
			fmt.Printf("Условие |b_%d| >= |a_%d| + |c_%d| выполнено: %.2f >= %.2f\n", i+1, i+1, i+1, left, right)
		}
	}

	// Проверка дополнительных условий:
	// |c1 / b1| < 1
	// |an / bn| < 1

	if n > 0 {
		cond1 := math.Abs(c[0] / b[0])
		if cond1 >= 1.0 {
			fmt.Printf("Условие |c1/b1| < 1 нарушено: %.6f >= 1.0\n", cond1)
			allStable = false
		} else {
			fmt.Printf("Условие |c1/b1| < 1 выполнено: %.6f < 1.0\n", cond1)
		}
	}

	if n > 0 {
		cond2 := math.Abs(a[n-1] / b[n-1])
		if cond2 >= 1.0 {
			fmt.Printf("Условие |a%d/b%d| < 1 нарушено: %.6f >= 1.0\n", n, n, cond2)
			allStable = false
		} else {
			fmt.Printf("Условие |a%d/b%d| < 1 выполнено: %.6f < 1.0\n", n, n, cond2)
		}
	}

	if allStable {
		fmt.Println("\nВсе условия устойчивости метода прогонки выполнены.")
	} else {
		fmt.Println("\nУсловия устойчивости метода прогонки НЕ ВЫПОЛНЕНЫ. Результат может быть неточным!")
	}

	if !allStable {
	    return
	}

	// Метод прогонки

	P := make([]float64, n)
	Q := make([]float64, n)

	// Первое уравнение: b[0]*x[0] + c[0]*x[1] = d[0]
	// => x[0] = P[0]*x[1] + Q[0]
	P[0] = -c[0] / b[0]
	Q[0] = d[0] / b[0]

	// Прямой ход
	for i := 1; i < n; i++ {
		denom := b[i] + a[i]*P[i-1]
		P[i] = -c[i] / denom
		Q[i] = (d[i] - a[i]*Q[i-1]) / denom
	}

	// Определитель = произведение диагональных элементов после исключения
	det := 1.0
	// Для i=0: denom = b[0] + a[0]*P[-1], но a[0] = 0 -> denom = b[0]
	det *= b[0] // первый шаг
	for i := 1; i < n; i++ {
		denom := b[i] + a[i]*P[i-1]
		det *= denom
	}
	fmt.Printf("\nОпределитель матрицы: %.6f\n", det)

	// Обратный ход
	x := make([]float64, n)
	x[n-1] = Q[n-1] // последнее уравнение: x[n-1] = Q[n-1] (т.к. c[n-1] = 0)
	for i := n - 2; i >= 0; i-- {
		x[i] = P[i]*x[i+1] + Q[i]
	}

	// Вывод решения
	fmt.Println("\nРешение системы:")
	for i := 0; i < n; i++ {
		fmt.Printf("x%d = %.6f\n", i+1, x[i])
	}
}